// arithmatic operators
let a = 10;
let b = 5;
let c = a + b; // Addition
let d = a - b; // Subtraction
let e = a * b; // Multiplication
let f = a / b; // Division
let g = a % b; // Modulus

// comparison operators
let x = 10;
let y = 5;
let z = x > y; // Greater than
let w = x < y; // Less than
let v = x >= y; // Greater than or equal to
let u = x <= y; // Less than or equal to
let t = x === y; // Strict equality
let s = x !== y; // Strict inequality

// logical operators
let p = true;
let q = false;
let r = p && q; // Logical AND
let o = p || q; // Logical OR
let n = !p; // Logical NOT

// assignment operators
let m = 10;
m += 5; // Equivalent to m = m + 5
m -= 3; // Equivalent to m = m - 3
m *= 2; // Equivalent to m = m * 2
m /= 4; // Equivalent to m = m / 4
m %= 3; // Equivalent to m = m % 3